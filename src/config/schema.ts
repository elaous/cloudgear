import { encodePrototxt, parsePrototxt, type ProtoMessage } from "./prototxt";

// Mirrors cloudgear.proto.
export interface CloudgearConfig {
  project: string;
  provider: string;
  resource: ResourceSpec[];
  function: FunctionSpec[];
  invoker: string[];
  authenticated: "iam" | "none";
  certificate: CertificateSpec[];
  cdn?: CdnSpec;
  api?: ApiSpec;
  region?: string;
}

export interface SecretRefSpec {
  provider: string;
  service: string;
  region?: string;
  kms_key?: string;
  path: string;
  name: string;
}

export interface SecretBindingSpec extends SecretRefSpec {
  env: string;
  all?: boolean;
}

export interface DnsSpec {
  provider: string;
  domain: string;
  zone: string;
  token?: SecretRefSpec;
}

export type Options = Record<string, string>;

export interface CertificateSpec {
  provider: string;
  domain: string;
  dns: DnsSpec;
  usage?: "cdn" | "api";
  region?: string;
  options?: Options;
}

export interface ApiSpec {
  provider: string;
  domain: string;
  via?: "cloudfront";
  method_routing?: boolean;
  options?: Options;
}

export interface CdnSpec {
  provider: string;
  domain: string;
  bucket: string;
  path: string;
  options?: Options;
}

export interface ResourceSpec {
  name: string;
  type: string;
  physical_name: string;
  dry: boolean;
  source: string;
  region?: string;
  options?: Options;
}

export interface FunctionSpec {
  name: string;
  type: string;
  physical_name: string;
  runtime: string;
  memory_mb: number;
  timeout_s: number;
  source: { file: string; export: string; member?: string; input_type?: string };
  route: { method: string; path: string; name: string }[];
  bundle: { path: string; sha256: string };
  permission: { resource: string; path: string; action: string[] }[];
  // value_from names a resource whose physical name becomes the value.
  env: { key: string; value?: string; value_from?: string }[];
  reserved_concurrency: number;
  options?: Options;
  schedule?: string[];
  include?: string[];
  pass_request?: boolean;
  response_arg?: "helper" | "writer";
  secret?: SecretBindingSpec[];
}

const REPEATED = new Set([
  "resource",
  "function",
  "function.route",
  "function.permission",
  "function.permission.action",
  "function.env",
  "invoker",
  "certificate",
  "resource.options",
  "function.options",
  "function.schedule",
  "function.secret",
  "function.include",
  "certificate.options",
  "api.options",
  "cdn.options",
]);

export function encodeConfig(config: CloudgearConfig): string {
  return encodePrototxt(optionsToProto(config) as ProtoMessage, [
    "proto-file: cloudgear.proto",
    "proto-message: cloudgear.Config",
    "Generated by `cloudgear generate`. Do not edit by hand.",
  ]);
}

export function decodeConfig(text: string): CloudgearConfig {
  const raw = parsePrototxt(text, REPEATED) as Record<string, any>;
  const config: CloudgearConfig = {
    project: str(raw, "project"),
    provider: str(raw, "provider"),
    invoker: (raw.invoker ?? []).map(String),
    authenticated: raw.authenticated === "none" ? "none" : "iam",
    region: raw.region ? String(raw.region) : undefined,
    certificate: (raw.certificate ?? []).map((c: Record<string, any>) => ({
      provider: String(c.provider ?? "aws"),
      domain: str(c, "domain"),
      dns: {
        provider: str(c.dns ?? {}, "provider"),
        domain: str(c.dns ?? {}, "domain"),
        zone: str(c.dns ?? {}, "zone"),
        ...(c.dns?.token ? { token: secretRefFrom(c.dns.token) } : {}),
      },
      ...(c.usage === "cdn" || c.usage === "api" ? { usage: c.usage } : {}),
      ...(c.region ? { region: String(c.region) } : {}),
      ...optionsFrom(c),
    })),
    cdn: raw.cdn && {
      provider: str(raw.cdn, "provider"),
      domain: str(raw.cdn, "domain"),
      bucket: str(raw.cdn, "bucket"),
      path: String(raw.cdn.path ?? ""),
      ...optionsFrom(raw.cdn),
    },
    api: raw.api && {
      provider: str(raw.api, "provider"),
      domain: str(raw.api, "domain"),
      ...(raw.api.via === "cloudfront" ? { via: "cloudfront" as const } : {}),
      ...(raw.api.method_routing === true ? { method_routing: true } : {}),
      ...optionsFrom(raw.api),
    },
    resource: (raw.resource ?? []).map((r: Record<string, any>) => ({
      name: str(r, "name"),
      type: str(r, "type"),
      physical_name: str(r, "physical_name"),
      dry: r.dry === true,
      source: r.source ?? "",
      region: r.region ? String(r.region) : undefined,
      ...optionsFrom(r),
    })),
    function: (raw.function ?? []).map((f: Record<string, any>) => ({
      name: str(f, "name"),
      type: str(f, "type"),
      physical_name: str(f, "physical_name"),
      runtime: str(f, "runtime"),
      memory_mb: Number(f.memory_mb ?? 128),
      timeout_s: Number(f.timeout_s ?? 10),
      source: {
        file: str(f.source ?? {}, "file"),
        export: str(f.source ?? {}, "export"),
        member: f.source?.member,
        input_type: f.source?.input_type,
      },
      route: (f.route ?? []).map((r: Record<string, any>) => ({ method: str(r, "method"), path: str(r, "path"), name: String(r.name ?? "") })),
      bundle: { path: str(f.bundle ?? {}, "path"), sha256: str(f.bundle ?? {}, "sha256") },
      permission: (f.permission ?? []).map((p: Record<string, any>) => ({
        resource: str(p, "resource"),
        path: String(p.path ?? ""),
        action: (p.action ?? []).map(String),
      })),
      env: (f.env ?? []).map((e: Record<string, any>) =>
        e.value_from !== undefined ? { key: str(e, "key"), value_from: str(e, "value_from") } : { key: str(e, "key"), value: String(e.value ?? "") },
      ),
      reserved_concurrency: Number(f.reserved_concurrency ?? 0),
      ...(f.schedule?.length ? { schedule: f.schedule.map(String) } : {}),
      ...(f.include?.length ? { include: f.include.map(String) } : {}),
      ...(f.pass_request === true ? { pass_request: true } : {}),
      ...(f.response_arg === "helper" || f.response_arg === "writer" ? { response_arg: f.response_arg } : {}),
      ...(f.secret?.length ? { secret: f.secret.map((s: Record<string, any>) => ({ ...secretRefFrom(s), env: String(s.env ?? ""), ...(s.all === true ? { all: true } : {}) })) } : {}),
      ...optionsFrom(f),
    })),
  };
  return config;
}

function secretRefFrom(raw: Record<string, any>): SecretRefSpec {
  return {
    provider: String(raw.provider ?? "aws"),
    service: String(raw.service ?? "ssm"),
    ...(raw.region ? { region: String(raw.region) } : {}),
    ...(raw.kms_key ? { kms_key: String(raw.kms_key) } : {}),
    path: str(raw, "path"),
    name: String(raw.name ?? ""),
  };
}

// A proto map is written as repeated { key, value } entries.
function optionsToProto(config: CloudgearConfig): unknown {
  const entries = (options?: Options) => (options && Object.keys(options).length ? Object.entries(options).sort(([a], [b]) => a.localeCompare(b)).map(([key, value]) => ({ key, value })) : undefined);
  const withOptions = <T extends { options?: Options }>(item: T) => ({ ...item, options: entries(item.options) });
  return {
    ...config,
    resource: config.resource.map(withOptions),
    function: config.function.map(withOptions),
    certificate: config.certificate.map(withOptions),
    cdn: config.cdn && withOptions(config.cdn),
    api: config.api && withOptions(config.api),
  };
}

function optionsFrom(message: Record<string, any>): { options?: Options } {
  const entries = (message.options ?? []) as Record<string, any>[];
  return entries.length ? { options: Object.fromEntries(entries.map((e) => [str(e, "key"), String(e.value ?? "")])) } : {};
}

function str(message: Record<string, any>, field: string): string {
  const value = message[field];
  if (typeof value !== "string") throw new Error(`cloudgear config: missing string field "${field}"`);
  return value;
}
