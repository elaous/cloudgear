import { assertSecretName, parseSecretPath } from "@cloudgear/secrets";
import { encodePrototxt, parsePrototxt, type ProtoMessage } from "./prototxt";

// Keep in sync with cloudgear.proto.
export interface CloudgearConfig {
  project: string;
  provider: string;
  resource: ResourceSpec[];
  function: FunctionSpec[];
  invoker: string[];
  authenticated: "iam" | "none";
  certificate: CertificateSpec[];
  cdn: CdnSpec[];
  api?: ApiSpec;
  region?: string;
}

export interface SecretRefSpec {
  provider: string;
  service: string;
  region?: string;
  kms_key?: string;
  path: string;
  name: string;
}

export interface SecretBindingSpec extends SecretRefSpec {
  env: string;
  all?: boolean;
}

export interface DnsSpec {
  provider: string;
  domain: string;
  zone: string;
  token?: SecretRefSpec;
}

export type Options = Record<string, string>;

export interface CertificateSpec {
  provider: string;
  domain: string;
  dns: DnsSpec;
  usage?: "cdn" | "api";
  region?: string;
  options?: Options;
}

export interface AttachedBehaviorSpec {
  path_pattern: string;
  // CloudFront CacheBehavior as JSON.
  behavior: string;
  position?: number;
}

export interface AttachedOriginSpec {
  id: string;
  // CloudFront Origin as JSON.
  origin: string;
  behavior: AttachedBehaviorSpec[];
}

export interface ApiSpec {
  provider: string;
  domain: string;
  certificate?: string;
  via?: "cloudfront";
  method_routing?: boolean;
  options?: Options;
  attached?: AttachedOriginSpec[];
}

export interface CdnSpec {
  provider: string;
  domain: string;
  certificate?: string;
  bucket: string;
  path: string;
  options?: Options;
  attached?: AttachedOriginSpec[];
}

export interface ResourceSpec {
  name: string;
  type: string;
  physical_name: string;
  dry: boolean;
  source: string;
  region?: string;
  options?: Options;
}

export interface FunctionSpec {
  name: string;
  type: string;
  physical_name: string;
  runtime: string;
  memory_mb: number;
  timeout_s: number;
  source: { file: string; export: string; member?: string; input_type?: string };
  route: { method: string; path: string; name: string }[];
  bundle: { path: string; sha256: string };
  permission: { resource: string; path: string; action: string[] }[];
  // The named resource's physical name becomes the value.
  env: { key: string; value?: string; value_from?: string }[];
  reserved_concurrency: number;
  options?: Options;
  schedule?: string[];
  include?: string[];
  pass_request?: boolean;
  response_arg?: "helper" | "writer";
  secret?: SecretBindingSpec[];
  event?: EventTriggerSpec[];
  query_schedule?: { cron: string; query: Record<string, string> }[];
  policy?: { name: string; document: string }[];
}

export interface EventTriggerSpec {
  bus: string;
  type: string;
  source?: string;
}

const REPEATED = new Set([
  "resource",
  "function",
  "function.route",
  "function.permission",
  "function.permission.action",
  "function.env",
  "invoker",
  "certificate",
  "cdn",
  "resource.options",
  "function.options",
  "function.schedule",
  "function.secret",
  "function.event",
  "function.policy",
  "function.query_schedule",
  "function.query_schedule.query",
  "function.include",
  "certificate.options",
  "api.options",
  "cdn.options",
  "api.attached",
  "api.attached.behavior",
  "cdn.attached",
  "cdn.attached.behavior",
]);

export function encodeConfig(config: CloudgearConfig): string {
  return encodePrototxt(optionsToProto(config) as ProtoMessage, [
    "proto-file: cloudgear.proto",
    "proto-message: cloudgear.Config",
    "Generated by `cloudgear generate`. Do not edit by hand.",
  ]);
}

export function decodeConfig(text: string): CloudgearConfig {
  const raw = parsePrototxt(text, REPEATED) as Record<string, any>;
  const config: CloudgearConfig = {
    project: str(raw, "project"),
    provider: str(raw, "provider"),
    invoker: (raw.invoker ?? []).map(String),
    authenticated: raw.authenticated === "none" ? "none" : "iam",
    region: raw.region ? String(raw.region) : undefined,
    certificate: (raw.certificate ?? []).map((c: Record<string, any>) => ({
      provider: String(c.provider ?? "aws"),
      domain: str(c, "domain"),
      dns: {
        provider: str(c.dns ?? {}, "provider"),
        domain: str(c.dns ?? {}, "domain"),
        zone: str(c.dns ?? {}, "zone"),
        ...(c.dns?.token ? { token: secretRefFrom(c.dns.token) } : {}),
      },
      ...(c.usage === "cdn" || c.usage === "api" ? { usage: c.usage } : {}),
      ...(c.region ? { region: String(c.region) } : {}),
      ...optionsFrom(c),
    })),
    cdn: (raw.cdn ?? []).map((c: Record<string, any>) => ({
      provider: str(c, "provider"),
      domain: str(c, "domain"),
      bucket: str(c, "bucket"),
      path: String(c.path ?? ""),
      ...(c.certificate ? { certificate: String(c.certificate) } : {}),
      ...optionsFrom(c),
      ...attachedFrom(c),
    })),
    api: raw.api && {
      provider: str(raw.api, "provider"),
      domain: str(raw.api, "domain"),
      ...(raw.api.certificate ? { certificate: String(raw.api.certificate) } : {}),
      ...(raw.api.via === "cloudfront" ? { via: "cloudfront" as const } : {}),
      ...(raw.api.method_routing === true ? { method_routing: true } : {}),
      ...optionsFrom(raw.api),
      ...attachedFrom(raw.api),
    },
    resource: (raw.resource ?? []).map((r: Record<string, any>) => ({
      name: str(r, "name"),
      type: str(r, "type"),
      physical_name: str(r, "physical_name"),
      dry: r.dry === true,
      source: r.source ?? "",
      region: r.region ? String(r.region) : undefined,
      ...optionsFrom(r),
    })),
    function: (raw.function ?? []).map((f: Record<string, any>) => ({
      name: str(f, "name"),
      type: str(f, "type"),
      physical_name: str(f, "physical_name"),
      runtime: str(f, "runtime"),
      memory_mb: Number(f.memory_mb ?? 128),
      timeout_s: Number(f.timeout_s ?? 10),
      source: {
        file: str(f.source ?? {}, "file"),
        export: str(f.source ?? {}, "export"),
        member: f.source?.member,
        input_type: f.source?.input_type,
      },
      route: (f.route ?? []).map((r: Record<string, any>) => ({ method: str(r, "method"), path: str(r, "path"), name: String(r.name ?? "") })),
      bundle: { path: str(f.bundle ?? {}, "path"), sha256: str(f.bundle ?? {}, "sha256") },
      permission: (f.permission ?? []).map((p: Record<string, any>) => ({
        resource: str(p, "resource"),
        path: String(p.path ?? ""),
        action: (p.action ?? []).map(String),
      })),
      env: (f.env ?? []).map((e: Record<string, any>) =>
        e.value_from !== undefined ? { key: str(e, "key"), value_from: str(e, "value_from") } : { key: str(e, "key"), value: String(e.value ?? "") },
      ),
      reserved_concurrency: Number(f.reserved_concurrency ?? 0),
      ...(f.schedule?.length ? { schedule: f.schedule.map(String) } : {}),
      ...(f.include?.length ? { include: f.include.map(String) } : {}),
      ...(f.pass_request === true ? { pass_request: true } : {}),
      ...(f.response_arg === "helper" || f.response_arg === "writer" ? { response_arg: f.response_arg } : {}),
      ...(f.secret?.length ? { secret: f.secret.map((s: Record<string, any>) => ({ ...secretRefFrom(s), env: String(s.env ?? ""), ...(s.all === true ? { all: true } : {}) })) } : {}),
      ...(f.query_schedule?.length
        ? {
            query_schedule: f.query_schedule.map((q: Record<string, any>) => ({
              cron: str(q, "cron"),
              query: Object.fromEntries(((q.query ?? []) as Record<string, any>[]).map((e) => [str(e, "key"), String(e.value ?? "")])),
            })),
          }
        : {}),
      ...(f.policy?.length ? { policy: f.policy.map((p: Record<string, any>) => ({ name: str(p, "name"), document: str(p, "document") })) } : {}),
      ...(f.event?.length
        ? { event: f.event.map((e: Record<string, any>) => ({ bus: str(e, "bus"), type: str(e, "type"), ...(e.source ? { source: String(e.source) } : {}) })) }
        : {}),
      ...optionsFrom(f),
    })),
  };
  return config;
}

const REGION = /^[a-z]{2}(-[a-z]+)+-\d$/;

function secretRefFrom(raw: Record<string, any>): SecretRefSpec {
  const service = String(raw.service ?? "ssm");
  if (service !== "ssm" && service !== "secretsmanager") throw new Error(`cloudgear config: unknown secret service "${service}"`);
  const { prefix, all } = parseSecretPath(str(raw, "path"));
  if (all) throw new Error(`cloudgear config: secret path "${raw.path}" must not end in /*`);
  const name = String(raw.name ?? "");
  if (name) assertSecretName(name);
  if (raw.region && !REGION.test(String(raw.region))) throw new Error(`cloudgear config: invalid secret region "${raw.region}"`);
  return {
    provider: String(raw.provider ?? "aws"),
    service,
    ...(raw.region ? { region: String(raw.region) } : {}),
    ...(raw.kms_key ? { kms_key: String(raw.kms_key) } : {}),
    path: prefix,
    name,
  };
}

// Proto maps are written as repeated key/value entries.
function optionsToProto(config: CloudgearConfig): unknown {
  const entries = (options?: Options) => (options && Object.keys(options).length ? Object.entries(options).sort(([a], [b]) => a.localeCompare(b)).map(([key, value]) => ({ key, value })) : undefined);
  const withOptions = <T extends { options?: Options }>(item: T) => ({ ...item, options: entries(item.options) });
  return {
    ...config,
    resource: config.resource.map(withOptions),
    function: config.function.map((f) => ({ ...withOptions(f), query_schedule: f.query_schedule?.map((q) => ({ cron: q.cron, query: entries(q.query) })) })),
    certificate: config.certificate.map(withOptions),
    cdn: config.cdn.map((c) => withOptions({ ...c, attached: c.attached?.length ? c.attached : undefined })),
    api: config.api && withOptions({ ...config.api, attached: config.api.attached?.length ? config.api.attached : undefined }),
  };
}

function attachedFrom(message: Record<string, any>): { attached?: AttachedOriginSpec[] } {
  const items = (message.attached ?? []) as Record<string, any>[];
  if (!items.length) return {};
  return {
    attached: items.map((item) => {
      const id = str(item, "id");
      const json = (text: string, what: string) => {
        try {
          const value = JSON.parse(text);
          if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error("not an object");
          return value as Record<string, unknown>;
        } catch (err) {
          throw new Error(`cloudgear config: attached origin "${id}": ${what} is not a JSON object (${(err as Error).message})`);
        }
      };
      const origin = String(item.origin ?? "");
      if (json(origin, "origin").Id !== id) throw new Error(`cloudgear config: attached origin "${id}": its origin JSON has another Id`);
      const behavior = ((item.behavior ?? []) as Record<string, any>[]).map((b) => {
        const path_pattern = str(b, "path_pattern");
        const text = String(b.behavior ?? "");
        const parsed = json(text, `behavior "${path_pattern}"`);
        if (parsed.PathPattern !== path_pattern) throw new Error(`cloudgear config: attached origin "${id}": behavior "${path_pattern}" has another PathPattern in its JSON`);
        if (parsed.TargetOriginId !== id) throw new Error(`cloudgear config: attached origin "${id}": behavior "${path_pattern}" targets another origin`);
        return { path_pattern, behavior: text, ...(b.position !== undefined ? { position: Number(b.position) } : {}) };
      });
      return { id, origin, behavior };
    }),
  };
}

function optionsFrom(message: Record<string, any>): { options?: Options } {
  const entries = (message.options ?? []) as Record<string, any>[];
  return entries.length ? { options: Object.fromEntries(entries.map((e) => [str(e, "key"), String(e.value ?? "")])) } : {};
}

function str(message: Record<string, any>, field: string): string {
  const value = message[field];
  if (typeof value !== "string") throw new Error(`cloudgear config: missing string field "${field}"`);
  return value;
}
