import { afterAll, beforeAll, describe, expect, setDefaultTimeout, test } from "bun:test";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { generate } from "../src/generate";

setDefaultTimeout(60_000);

// Copies of polymorph's testdata/*.setup.ts; refresh when they change.
const entry = path.join(import.meta.dir, "fixtures", "polymorph", "tranquilo", "setup.ts");

let dir: string;
beforeAll(() => {
  dir = fs.mkdtempSync(path.join(os.tmpdir(), "polymorph-"));
});
afterAll(() => fs.rmSync(dir, { recursive: true, force: true }));

let runs = 0;
const analyze = async (setupEnv: Record<string, string | undefined> = {}) =>
  generate({ entry, configPath: path.join(dir, `run-${runs++}.prototxt`), buildDir: path.join(dir, "build"), project: "tranquilo-app", setupEnv });

describe("setup.ts generated by polymorph", () => {
  test("names the file it came from", () => {
    const [first, second] = fs.readFileSync(entry, "utf8").split("\n");
    expect(first).toBe("// Generated by polymorph from tranquilo.polymorph; do not edit.");
    expect(second).toBe('// Project "tranquilo-app": run cloudgear generate with --project tranquilo-app.');
  });

  test("declares the domains and certificates with the env defaults", async () => {
    const { config } = await analyze();
    expect(config.certificate.map((c) => c.domain)).toEqual(["web.tranquilo.art", "cdn.prod.tranquilo.art", "api.tranquilo.art"]);
    expect(config.certificate.every((c) => c.dns.zone === "tranquilo.art" && c.dns.provider === "gandi")).toBe(true);
  });

  test("reads the environment: a variable changes the domains and the zone", async () => {
    const { config } = await analyze({ ENV_DOMAIN: "example.org", ENV_ZONE: "example.org" });
    expect(config.certificate.map((c) => c.domain)).toEqual(["web.example.org", "cdn.prod.example.org", "api.example.org"]);
    expect(config.certificate[0]!.dns.zone).toBe("example.org");
  });

  test("the site bucket uploads its directory and carries its CORS rules and cache headers", async () => {
    const { config } = await analyze();
    const site = config.resource.find((r) => r.name === "web.tranquilo.art")!;
    expect(site.type).toBe("@aws.S3");
    expect(JSON.parse(site.options!.cors!)).toEqual([{ origins: ["https://web.tranquilo.art"], methods: ["GET", "HEAD"], max_age_seconds: 3600 }]);
    expect(JSON.parse(site.options!.site_cache_control!)).toEqual([{ match: "assets/**", value: "public, max-age=31536000, immutable" }]);
    expect(site.options!.site_files_count).toBe("2");
    expect(site.options!.index_document).toBe("index.html");
    expect(config.resource.find((r) => r.name === "cdn.prod.tranquilo.art")!.options).toBeUndefined();
  });

  test("two CDNs serve the buckets and the API sits behind CloudFront with the same web ACL setting", async () => {
    const { config } = await analyze();
    expect(config.cdn.map((c) => [c.domain, c.bucket, c.options?.web_acl, c.options?.default_root_object])).toEqual([
      ["web.tranquilo.art", "web.tranquilo.art", "true", ""],
      ["cdn.prod.tranquilo.art", "cdn.prod.tranquilo.art", "true", ""],
    ]);
    expect(config.api).toMatchObject({ provider: "aws", domain: "api.tranquilo.art", via: "cloudfront", options: { web_acl: "true" } });
    expect(config.region).toBe("us-east-1");
    expect(config.authenticated).toBe("iam");
  });

  test("the routes become functions with their secrets, schedules and response writer", async () => {
    const { config } = await analyze();
    const [index, cron] = config.function;
    expect(index!.route.map((r) => `${r.method} ${r.path}`)).toEqual(["* /"]);
    expect(cron!.route.map((r) => `${r.method} ${r.path}`)).toEqual(["GET /api/cron"]);
    expect([index!.secret?.length, cron!.secret?.length]).toEqual([10, 12]);
    expect(index!.secret!.every((s) => s.path === "/cloudgear/tranquilo-app" && s.provider === "aws" && s.service === "ssm")).toBe(true);
    expect(index!.secret!.map((s) => s.env)).toContain("ITEMS_CURSOR_SECRET");
    expect(cron!.query_schedule).toHaveLength(6);
    expect(cron!.query_schedule!.map((s) => s.cron)).toContain("27 7 1 * *");
    expect([index!.pass_request, index!.response_arg, cron!.pass_request, cron!.response_arg]).toEqual([true, "writer", true, "writer"]);
    expect(index!.include).toEqual(["tests/fixtures/polymorph/tranquilo/dist/index.html"]);
  });

  test("the scan sees what the handlers read and how each variable is provided", async () => {
    const { env } = await analyze();
    const provided = (name: string) => Object.values(env.functions).map((fn) => fn.variables[name]?.provided).find((p) => p !== undefined);
    expect(provided("DATABASE_URL")).toBe("secret");
    expect(provided("CRON_SECRET")).toBe("secret");
    expect(provided("SENTRY_DSN")).toBe("secret");
  });

  test("only the known warnings are raised", async () => {
    const { warnings } = await analyze();
    expect(warnings.filter((w) => /contains dots/.test(w))).toHaveLength(2);
    expect(warnings.filter((w) => /x-amz-content-sha256/.test(w))).toHaveLength(1);
    expect(warnings.filter((w) => !/contains dots|x-amz-content-sha256/.test(w))).toEqual([]);
  });

});

describe("a second generated setup.ts: caches, networks, tokens and secret bindings", () => {
  const platform = path.join(import.meta.dir, "fixtures", "polymorph", "platform", "setup.ts");
  const analyzePlatform = (setupEnv: Record<string, string | undefined> = {}) =>
    generate({ entry: platform, configPath: path.join(dir, `run-${runs++}.prototxt`), buildDir: path.join(dir, "platform-build"), project: "platform", setupEnv });

  test("the cache runs in the network it describes", async () => {
    const { config } = await analyzePlatform();
    expect(config.resource).toHaveLength(1);
    expect(config.resource[0]).toMatchObject({
      name: "cache.sessions",
      type: "@aws.ElastiCache",
      options: { engine: "valkey", size: "small", vpc: "vpc-0123456789abcdef0", subnets: "subnet-0123456789abcdef0,subnet-0123456789abcdef1" },
    });
  });

  test("the DNS token is a secret and the certificate covers the router's domain", async () => {
    const { config } = await analyzePlatform();
    expect(config.certificate[0]).toMatchObject({ domain: "api.example.test", usage: "api", dns: { provider: "gandi", token: { path: "/gandi", name: "GANDI_TOKEN", service: "secretsmanager" } } });
    expect(config.authenticated).toBe("none");
  });

  test("the secret store region comes from the environment, with its default", async () => {
    expect((await analyzePlatform()).config.certificate[0]!.dns.token!.region).toBe("eu-west-1");
    expect((await analyzePlatform({ ENV_REGION: "us-east-2" })).config.certificate[0]!.dns.token!.region).toBe("us-east-2");
  });

  test("names, renamed secrets and an all binding become the function's secrets", async () => {
    const { config } = await analyzePlatform();
    const [health, tick] = config.function;
    expect(health!.secret!.map((s) => [s.path, s.env, s.name, s.all ?? false])).toEqual([
      ["/shared", "", "", true],
      ["/app", "API_KEY", "API_KEY", false],
      ["/app", "DB_URL", "database-url", false],
    ]);
    expect(tick!.secret!.map((s) => s.path)).toEqual(["/shared"]);
    expect(tick!.schedule).toEqual(["0 * * * *"]);
  });

  test("only the known warnings are raised", async () => {
    const { warnings } = await analyzePlatform();
    expect(warnings.filter((w) => /authenticated is "none"/.test(w))).toHaveLength(1);
    expect(warnings.filter((w) => /reads every secret under \/shared/.test(w))).toHaveLength(2);
    expect(warnings.filter((w) => !/authenticated is "none"|reads every secret under \/shared/.test(w))).toEqual([]);
  });

  test("the variables the handlers read are provided by the options and the bindings", async () => {
    const { env } = await analyzePlatform();
    const variables = Object.fromEntries(Object.values(env.functions).flatMap((fn) => Object.entries(fn.variables).map(([name, use]) => [name, use.provided])));
    expect(variables).toEqual({ API_KEY: "secret", STAGE: "option" });
  });

  test("the function options and the router network reach every function", async () => {
    const { config } = await analyzePlatform();
    for (const fn of config.function) expect(fn.options).toEqual({ "env.STAGE": "prod", vpc: "vpc-0123456789abcdef0" });
  });
});
